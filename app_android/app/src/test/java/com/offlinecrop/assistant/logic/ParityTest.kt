package com.offlinecrop.assistant.logic

import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Before
import org.junit.Test
import java.io.File

/**
 * ParityTest – Phase 4.4: JVM unit tests that read test_vectors/llm/parity.json
 * and assert that the Kotlin advisory pipeline reproduces all Python parity cases.
 *
 * Run with: ./gradlew testDebugUnitTest
 *
 * These tests run on the laptop JVM (no Android runtime needed).
 * The parity.json file is generated by tools/generate_parity_vectors.py.
 */
class ParityTest {

    private lateinit var kbJson: String
    private lateinit var rulesJson: String
    private lateinit var clarificationsJson: String
    private lateinit var phrasesJson: String
    private lateinit var pipeline: AdvisoryPipeline
    private lateinit var validator: AdvisoryValidator
    private lateinit var parityJson: JSONArray

    @Before
    fun setUp() {
        val repoRoot = findRepoRoot()

        kbJson = File(repoRoot, "app_android/app/src/main/assets/kb.json").readText()
        rulesJson = File(repoRoot, "app_android/app/src/main/assets/rules.json").readText()
        clarificationsJson = File(repoRoot, "app_android/app/src/main/assets/clarifications.json").readText()
        phrasesJson = File(repoRoot, "app_android/app/src/main/assets/phrases.json").readText()

        pipeline = AdvisoryPipeline(
            kbJson = kbJson,
            rulesJson = rulesJson,
            clarificationsJson = clarificationsJson,
            phrasesJson = phrasesJson,
            llmGenerate = null  // fallback mode — mirrors Python parity generation
        )

        validator = AdvisoryValidator(rulesJson)

        val parityFile = File(repoRoot, "test_vectors/llm/parity.json")
        assertTrue("parity.json not found at ${parityFile.absolutePath}", parityFile.exists())
        parityJson = JSONArray(parityFile.readText())
    }

    // -----------------------------------------------------------------------
    // Main parity test: Kotlin pipeline matches Python expected output
    // -----------------------------------------------------------------------

    @Test
    fun `all parity cases reproduce Python output`() {
        var casesPassed = 0
        val failures = mutableListOf<String>()

        for (i in 0 until parityJson.length()) {
            val case_ = parityJson.getJSONObject(i)
            val caseId = case_.getString("id")
            val expected = case_.getJSONObject("expected")
            val request = case_.getJSONObject("input")

            try {
                val actual = pipeline.advise(request)
                assertCase(caseId, expected, actual)
                casesPassed++
            } catch (e: AssertionError) {
                failures.add("[$caseId] ${e.message}")
            }
        }

        if (failures.isNotEmpty()) {
            fail(
                "Parity failures (${ failures.size } of ${ parityJson.length() }):\n" +
                    failures.joinToString("\n")
            )
        }
        println("ParityTest: $casesPassed / ${parityJson.length()} cases passed.")
    }

    // -----------------------------------------------------------------------
    // Validator cases: check rejection reasons
    // -----------------------------------------------------------------------

    @Test
    fun `validator cases match Python decisions`() {
        var total = 0
        val failures = mutableListOf<String>()

        for (i in 0 until parityJson.length()) {
            val case_ = parityJson.getJSONObject(i)
            val caseId = case_.getString("id")
            val validatorCasesArr = case_.optJSONArray("validator_cases") ?: continue
            if (validatorCasesArr.length() == 0) continue

            for (j in 0 until validatorCasesArr.length()) {
                total++
                val vc = validatorCasesArr.getJSONObject(j)
                val llmOutput = vc.getString("llm_output")
                val conditionId = vc.getString("condition_id")
                val severityBand = vc.getString("severity_band")
                val expectedValid = vc.getBoolean("expected_valid")
                val expectedReasonContains = vc.optString("expected_reason_contains", "")
                val vcId = "$caseId[$j]"

                try {
                    val result = validator.validate(llmOutput, conditionId, severityBand)
            assertEquals(
                "[$vcId] expected isValid=$expectedValid", expectedValid, result.isValid)
            if (!expectedValid && expectedReasonContains.isNotBlank()) {
                val reasonsText = result.rejectionReasons.joinToString("; ").lowercase()
                assertTrue(
                    "[$vcId] expected rejection reason to contain '${expectedReasonContains.lowercase()}' but got: $reasonsText",
                    reasonsText.contains(expectedReasonContains.lowercase())
                )
            }
                } catch (e: AssertionError) {
                    failures.add(e.message ?: vcId)
                }
            }
        }

        if (failures.isNotEmpty()) {
            fail("Validator failures (${failures.size} of $total):\n" + failures.joinToString("\n"))
        }
        println("Validator cases: $total passed.")
    }

    // -----------------------------------------------------------------------
    // Asset drift detection: hashes must match tools/asset_hashes.json
    // -----------------------------------------------------------------------

    @Test
    fun `asset files match recorded hashes`() {
        val repoRoot = findRepoRoot()
        val hashFile = File(repoRoot, "tools/asset_hashes.json")
        if (!hashFile.exists()) {
            println("WARN: asset_hashes.json not found – run tools/export_for_android.py first. Skipping hash check.")
            return
        }

        val hashes = JSONObject(hashFile.readText())
        val assetsDir = File(repoRoot, "app_android/app/src/main/assets")
        val keys = hashes.keys()
        while (keys.hasNext()) {
            val filename = keys.next()
            val expected = hashes.getString(filename)
            val assetFile = File(assetsDir, filename)
            assertTrue("Asset $filename missing", assetFile.exists())
            val actual = sha256Hex(assetFile.readBytes())
            assertEquals(
                "Asset $filename hash mismatch. Run tools/export_for_android.py to regenerate.",
                expected, actual
            )
        }
        println("Asset hash check passed for ${hashes.length()} files.")
    }

    // -----------------------------------------------------------------------
    // Helpers
    // -----------------------------------------------------------------------

    private fun assertCase(caseId: String, expected: JSONObject, actual: AdvisoryResponseData) {
        val expStatus = expected.optString("status", "final")
        assertEquals("[$caseId] status", expStatus, actual.status)
        assertEquals("[$caseId] schema_version", expected.optString("schema_version", "1.0"), actual.schemaVersion)

        if (expStatus == "needs_clarification") {
            assertNotNull("[$caseId] clarification should be non-null for needs_clarification", actual.clarification)
            assertEquals(
                "[$caseId] clarification.question_id",
                expected.getJSONObject("clarification").getString("question_id"),
                actual.clarification?.questionId
            )
        } else {
            // For final responses, check key fields
            assertEquals("[$caseId] seek_help", expected.optBoolean("seek_help", false), actual.seekHelp)
            assertEquals("[$caseId] used_fallback", expected.optBoolean("used_fallback", true), actual.usedFallback)
            assertEquals("[$caseId] severity_band", expected.optString("severity_band", "none"), actual.severityBand)
            assertTrue("[$caseId] diagnosis should not be blank", actual.diagnosis.isNotBlank())
            assertTrue("[$caseId] text should not be blank", actual.text.isNotBlank())
            // Actions and prevention are present for non-unknown
            if (!expected.optBoolean("seek_help", false)) {
                assertTrue("[$caseId] actionsNow should not be empty", actual.actionsNow.isNotEmpty())
            }
        }
    }

    private fun sha256Hex(bytes: ByteArray): String {
        val md = java.security.MessageDigest.getInstance("SHA-256")
        val digest = md.digest(bytes)
        return digest.joinToString("") { "%02x".format(it) }
    }

    /**
     * Walks up from the test class location to find the repo root
     * (the directory containing AGENTS.md).
     */
    private fun findRepoRoot(): File {
        // When running with Gradle, user.dir is usually the module or project dir
        var dir = File(System.getProperty("user.dir") ?: ".").absoluteFile
        repeat(10) {
            if (File(dir, "AGENTS.md").exists()) return dir
            dir = dir.parentFile ?: return dir
        }
        // Fallback: try known absolute path (Windows dev machine)
        val hardcoded = File("D:/bits/projects/AiSoc")
        if (File(hardcoded, "AGENTS.md").exists()) return hardcoded
        return File(System.getProperty("user.dir") ?: ".")
    }
}
